def expand_versions():
    """展开为扁平的教材版本清单行。"""
    rows = []
    for d in VERSION_DEFS:
        pub = PUBLISHERS[d["出版社"]]
        base_url = CATALOG_BASE.get(d["目录"], CATALOG_BASE["国家平台"])
        for grade, vol in d["册别"]:
            name = f"{d['系列']} {d['学科']} {vol}"
            rows.append({
                "学段": d["学段"],
                "年级": grade,
                "学科": d["学科"],
                "教材名称": name,
                "出版社": pub,
                "版本标识": d["版本标识"],
                "册别": vol,
                "教材目录页URL": base_url,
            })
    return rows


