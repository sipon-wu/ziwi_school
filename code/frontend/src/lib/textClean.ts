/**
 * 展示文本清理（**缺省规则** · 2026-09-15）
 *
 * 为什么要有它：模型经常把 markdown 标记当**装饰**写进正文，而我们的展示层只认"行首列表符"，
 * 于是标记直接印在投屏/手机页上。实测（《琥珀 09-15》H5，11 页里 6 页中招）：
 *   模型写 `- > 地球46亿岁，人类才200万年。`（用 `>` 当引用装饰）
 *   → 只剥 `- ` 后剩下 `>` → 手机上旁白显示成「> 地球46亿岁，人类才200万年。」
 *   → 而且这些 `>` 会把同一段落切成碎片（多条要点被当成一段读）
 *
 * 规则：**行首的列表符（- * •）与引用符（> 一个或多个）一律剥掉**；行尾孤立的 `>` 也去掉。
 * 这是渲染层的兜底，不依赖模型守规矩（与「缺省规则不是提示词要求」同一原则）。
 * PPT 元素文本与 H5 场景文本共用本函数，保证两端看到的一致。
 */
export function stripDecorMarkers(s: unknown): string {
  const txt = s == null ? '' : String(s)
  return txt
    .split('\n')
    .map((line) =>
      line
        .replace(/^[\s\u3000]*[-*•]\s+/, '')   // 行首列表符
        .replace(/^[\s\u3000]*>+\s*/, '')      // 行首引用符（一个或多个）
        .replace(/[\s\u3000]+>\s*$/, '')       // 行尾孤立的 >
        .trim(),
    )
    .join('\n')
}
